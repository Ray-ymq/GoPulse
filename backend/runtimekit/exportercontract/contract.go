// Package exportercontract contains the small wire contract shared by an
// Exporter and the process manager. It deliberately does not know anything
// about a data source or its configuration fields.
package exportercontract

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"strconv"
	"strings"
)

const (
	// MaxConfigBytes bounds both management requests and the private file handed
	// to an Exporter. The process manager applies the same bound before writing.
	MaxConfigBytes = 64 << 10
	RuntimeVersion = 1
)

// Runtime is the part of an execution configuration owned by Monitor. The
// source-specific Config and Secrets objects are intentionally opaque here.
type Runtime struct {
	Mode            string `json:"mode"`
	ListenHost      string `json:"listen_host"`
	ListenPort      int    `json:"listen_port"`
	ConnectTimeout  string `json:"connect_timeout"`
	ScrapeTimeout   string `json:"scrape_timeout"`
	ShutdownTimeout string `json:"shutdown_timeout"`
}

// Envelope is the file format passed to check-config, check-connection and
// serve. Secrets are kept in a separate object so Monitor can persist the
// public revision without putting credentials in config.json or API DTOs.
type Envelope struct {
	Config     json.RawMessage
	Secrets    json.RawMessage
	Runtime    Runtime
	HasRuntime bool
}

// ReadFile reads and strictly decodes an Exporter configuration file.
func ReadFile(path string) (Envelope, error) {
	info, err := os.Stat(path)
	if err != nil || !info.Mode().IsRegular() || info.Size() > MaxConfigBytes {
		return Envelope{}, errors.New("invalid configuration")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return Envelope{}, errors.New("invalid configuration")
	}
	return Read(data)
}

// Read decodes a complete runtime file. Duplicate keys and unknown fields are
// rejected before typed decoding so each module receives one unambiguous input.
func Read(data []byte) (Envelope, error) {
	if len(data) == 0 || len(data) > MaxConfigBytes || !uniqueJSON(data) {
		return Envelope{}, errors.New("invalid configuration")
	}
	var fields map[string]json.RawMessage
	if err := decodeStrict(data, &fields); err != nil || fields == nil {
		return Envelope{}, errors.New("invalid configuration")
	}
	for key := range fields {
		if key != "config" && key != "secrets" && key != "runtime" {
			return Envelope{}, errors.New("invalid configuration")
		}
	}
	config, ok := fields["config"]
	if !ok || !isObject(config) {
		return Envelope{}, errors.New("invalid configuration")
	}
	secrets := fields["secrets"]
	if len(secrets) == 0 {
		secrets = []byte(`{}`)
	}
	if !isObject(secrets) {
		return Envelope{}, errors.New("invalid configuration")
	}
	envelope := Envelope{Config: append(json.RawMessage(nil), config...), Secrets: append(json.RawMessage(nil), secrets...)}
	if runtimeData, ok := fields["runtime"]; ok {
		if !isObject(runtimeData) {
			return Envelope{}, errors.New("invalid configuration")
		}
		if err := decodeStrict(runtimeData, &envelope.Runtime); err != nil {
			return Envelope{}, errors.New("invalid configuration")
		}
		envelope.HasRuntime = true
	}
	return envelope, nil
}

// ReadManagement accepts the public management DTO. Runtime is generated by
// Monitor and therefore cannot be supplied by a caller.
func ReadManagement(data []byte) (config, secrets json.RawMessage, hasSecrets bool, err error) {
	envelope, err := Read(data)
	if err != nil {
		return nil, nil, false, err
	}
	if envelope.HasRuntime {
		return nil, nil, false, errors.New("invalid configuration")
	}
	return envelope.Config, envelope.Secrets, len(bytes.TrimSpace(envelope.Secrets)) != 2, nil
}

// Encode creates a complete file from the two private revision objects and a
// manager-owned runtime section.
func Encode(config, secrets json.RawMessage, runtime Runtime) ([]byte, error) {
	if !isObject(config) || !isObject(secrets) {
		return nil, errors.New("invalid configuration")
	}
	value := struct {
		Config  json.RawMessage `json:"config"`
		Secrets json.RawMessage `json:"secrets"`
		Runtime Runtime         `json:"runtime"`
	}{config, secrets, runtime}
	data, err := json.Marshal(value)
	if err != nil || len(data) > MaxConfigBytes {
		return nil, errors.New("invalid configuration")
	}
	return append(data, '\n'), nil
}

// Object exposes a source-independent JSON object as raw fields. Exporter
// modules use it to apply their own field names and cross-field rules.
func Object(data json.RawMessage) (map[string]json.RawMessage, error) {
	if !isObject(data) || !uniqueJSON(data) {
		return nil, errors.New("invalid configuration")
	}
	var fields map[string]json.RawMessage
	if err := decodeStrict(data, &fields); err != nil || fields == nil {
		return nil, errors.New("invalid configuration")
	}
	return fields, nil
}

func String(fields map[string]json.RawMessage, name string, required bool) (string, error) {
	raw, ok := fields[name]
	if !ok {
		if required {
			return "", fmt.Errorf("missing field %s", name)
		}
		return "", nil
	}
	var value string
	if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) || json.Unmarshal(raw, &value) != nil {
		return "", fmt.Errorf("invalid field %s", name)
	}
	return value, nil
}

func Integer(fields map[string]json.RawMessage, name string, required bool) (int, error) {
	raw, ok := fields[name]
	if !ok {
		if required {
			return 0, fmt.Errorf("missing field %s", name)
		}
		return 0, nil
	}
	var value int
	if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) || json.Unmarshal(raw, &value) != nil {
		return 0, fmt.Errorf("invalid field %s", name)
	}
	return value, nil
}

// RuntimeEnvironment converts only manager-owned fields to the legacy process
// environment while modules migrate their implementation. No source-specific
// configuration field is interpreted here.
func RuntimeEnvironment(prefix string, runtime Runtime) map[string]string {
	values := map[string]string{"GOPULSE_RUNTIME_MODE": runtime.Mode}
	if values["GOPULSE_RUNTIME_MODE"] == "" {
		values["GOPULSE_RUNTIME_MODE"] = "host"
	}
	if runtime.ListenHost != "" {
		values[prefix+"_EXPORTER_HTTP_HOST"] = runtime.ListenHost
	}
	if runtime.ListenPort > 0 {
		values[prefix+"_EXPORTER_HTTP_PORT"] = strconv.Itoa(runtime.ListenPort)
	}
	if runtime.ConnectTimeout != "" {
		values[prefix+"_EXPORTER_CONNECT_TIMEOUT"] = runtime.ConnectTimeout
	}
	if runtime.ScrapeTimeout != "" {
		values[prefix+"_EXPORTER_SCRAPE_TIMEOUT"] = runtime.ScrapeTimeout
	}
	if runtime.ShutdownTimeout != "" {
		values[prefix+"_EXPORTER_SHUTDOWN_TIMEOUT"] = runtime.ShutdownTimeout
	}
	return values
}

// LoadWithEnvironment lets a file-based command reuse an existing typed loader
// without mutating the parent process after the command returns.
func LoadWithEnvironment[T any](values map[string]string, load func() (T, error)) (T, error) {
	old := make(map[string]*string, len(values))
	for key, value := range values {
		if previous, ok := os.LookupEnv(key); ok {
			copy := previous
			old[key] = &copy
		} else {
			old[key] = nil
		}
		if err := os.Setenv(key, value); err != nil {
			var zero T
			return zero, err
		}
	}
	defer func() {
		for key, previous := range old {
			if previous == nil {
				_ = os.Unsetenv(key)
			} else {
				_ = os.Setenv(key, *previous)
			}
		}
	}()
	return load()
}

// Result writes the stable stdout result used by management subprocesses.
func Result(w io.Writer, valid bool, code string) error {
	value := struct {
		Valid     bool   `json:"valid"`
		Reachable *bool  `json:"reachable,omitempty"`
		Code      string `json:"code,omitempty"`
	}{Valid: valid, Code: code}
	if code == "target_unavailable" {
		reachable := false
		value.Reachable = &reachable
	}
	if valid && code == "ok" {
		reachable := true
		value.Reachable = &reachable
	}
	data, err := json.Marshal(value)
	if err != nil {
		return err
	}
	_, err = w.Write(append(data, '\n'))
	return err
}

func isObject(data []byte) bool {
	trimmed := bytes.TrimSpace(data)
	return len(trimmed) >= 2 && trimmed[0] == '{' && trimmed[len(trimmed)-1] == '}' && json.Valid(trimmed)
}

func decodeStrict(data []byte, out any) error {
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(out); err != nil {
		return err
	}
	_, err := decoder.Token()
	if errors.Is(err, io.EOF) {
		return nil
	}
	return errors.New("trailing data")
}

func uniqueJSON(data []byte) bool {
	decoder := json.NewDecoder(bytes.NewReader(data))
	var walk func() bool
	walk = func() bool {
		token, err := decoder.Token()
		if err != nil {
			return false
		}
		delimiter, ok := token.(json.Delim)
		if !ok {
			return true
		}
		switch delimiter {
		case '{':
			seen := map[string]bool{}
			for decoder.More() {
				key, err := decoder.Token()
				name, ok := key.(string)
				if err != nil || !ok || seen[name] {
					return false
				}
				seen[name] = true
				if !walk() {
					return false
				}
			}
			end, err := decoder.Token()
			return err == nil && end == json.Delim('}')
		case '[':
			for decoder.More() {
				if !walk() {
					return false
				}
			}
			end, err := decoder.Token()
			return err == nil && end == json.Delim(']')
		default:
			return false
		}
	}
	if !walk() {
		return false
	}
	_, err := decoder.Token()
	return errors.Is(err, io.EOF) && strings.TrimSpace(string(data)) != ""
}
